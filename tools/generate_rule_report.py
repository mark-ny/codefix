#!/usr/bin/env python3
"""Generate a Markdown reference of every rule (docs/rules.md by default)."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from codefix.config import load_config  # noqa: E402
from codefix.knowledge.registry import build_registry  # noqa: E402


def render(specs) -> str:
    out = ["# Rule reference", "", "_Generated by `tools/generate_rule_report.py`._", "",
           "| Rule | Category | Severity | Confidence | Autofix | Tests required |", "|---|---|---|---|---|---|"]
    for s in specs:
        out.append(f"| [`{s.id}`](#{s.id.lower()}) | {s.category} | {s.severity.value} | {s.confidence:.2f} | "
                   f"{'yes' if s.autofix else 'no'} | {'yes' if s.requires_tests else 'no'} |")
    for s in specs:
        out += ["", f"## {s.id}", "", s.message, "", s.explanation or s.description, ""]
        if s.bad:
            out += ["Bad:", "```python", s.bad.rstrip("\n"), "```", "Good:", "```python", s.good.rstrip("\n"), "```"]
        if s.false_positive:
            out += ["", f"**False positives:** {s.false_positive}"]
        if not s.implemented:
            out += ["", "_Documentation only: no analyzer is registered._"]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-o", "--output", default="docs/rules.md")
    args = ap.parse_args()
    reg = build_registry(load_config("."))
    Path(args.output).write_text(render(reg.specs()), encoding="utf-8")
    print(f"wrote {args.output} ({len(reg.specs())} rules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
